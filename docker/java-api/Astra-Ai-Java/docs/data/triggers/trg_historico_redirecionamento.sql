-- TRIGGER para validar o redirecionamento de uma rectenna para outra em caso de clima adverso
CREATE OR REPLACE TRIGGER TRG_HISTORICO_REDIRECIONAMENTO
BEFORE INSERT ON AST_HISTORICO_CONEXAO
FOR EACH ROW
BEGIN
    PKG_GESTAO_CONEXOES.VALIDAR_REDIRECIONAMENTO(:NEW.ID_SATELITE, :NEW.ID_RECTENNA);
END;
